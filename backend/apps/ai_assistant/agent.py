import json
import logging
from typing import Any, Dict, List, Optional

from django.utils import timezone

from apps.accounts.models import User
from .groq_client import groq_client
from .tools import COPILOT_TOOLS, execute_tool

logger = logging.getLogger(__name__)


def build_system_prompt(user: User) -> str:
    now_local = timezone.localtime(timezone.now())
    role_label = getattr(user, "get_role_display", lambda: user.role)()
    dept = getattr(user.department, "name", "General Campus") if getattr(user, "department", None) else "General Campus"
    user_name = user.get_full_name() or user.username

    return f"""You are "Campus Copilot", the intelligent AI Concierge for BookMyCampus at Lovely Professional University (LPU).

### Current Environment & Campus Context:
- Current Campus Time: {now_local.strftime('%A, %d %B %Y, %H:%M (IST)')}
- Active User: {user_name} ({user.email})
- User Role: {role_label} (role key: {user.role})
- Department: {dept}
- LPU Campus Blocks: Block 32, Block 34 (Computer Science & IT), Block 36 (Engineering), Block 38 (Management & Arts), Central Library, Uni-Mall, Shanti Devi Mittal Auditorium, Central Robotics Lab.

### Core Guidelines & Capabilities:
1. You have direct programmatic access to campus tools: searching rooms, inspecting real-time schedules, checking bookings, booking rooms, cancelling reservations, reporting equipment maintenance, and checking hourly block vacancy.
2. ALWAYS call tools when the user asks about availability, bookings, or campus resources. NEVER guess, assume, or hallucinate room codes, vacancy percentages, or booking references.
3. Understand natural language queries like:
   - "Find a room with a projector in Block 34 for 30 students today from 4 to 6 PM"
   - "What are my upcoming bookings?"
   - "The projector in Room 34-204 is broken, report it"
   - "Which building has the most free rooms right now?"
4. Role-aware bookings:
   - Students book for themselves: classrooms (HOD approval), meeting rooms, sports facilities and equipment.
   - Laboratories, seminar halls and vehicles are booked by faculty and staff only. If a student asks for one, say so and suggest they ask their teacher. Do not try to book it for them.
   - Some types need HOD approval (equipment, seminar halls, vehicles, and classrooms for students). Tell the user when a request will wait for approval.
5. Tone & Formatting:
   - Be concise, modern, warm, and professional.
   - Use Markdown (bold headers, bullet points).
   - If interactive UI cards are generated by tools (like room recommendation cards or booking passes), the web frontend renders them automatically directly below your answer. Keep your text focused on helpful context and next steps.
"""


class CampusCopilotAgent:
    """
    Autonomous ReAct Agent executing multi-turn reasoning and tool calling
    with Groq high-speed LPU inference and multi-key failover.
    """

    MAX_ITERATIONS = 5

    def run(
        self,
        user: User,
        user_message: str,
        history: Optional[List[Dict[str, str]]] = None,
    ) -> Dict[str, Any]:
        system_prompt = build_system_prompt(user)

        working_messages: List[Dict[str, Any]] = [
            {"role": "system", "content": system_prompt}
        ]

        # Append sanitized conversation history (limit to last 10 messages for speed & tokens)
        if history:
            for item in history[-10:]:
                role = item.get("role")
                content = item.get("content")
                if role in ("user", "assistant") and content:
                    working_messages.append({"role": role, "content": str(content)})

        # Append new user message
        working_messages.append({"role": "user", "content": user_message})

        collected_cards: List[Dict[str, Any]] = []
        tools_executed: List[str] = []
        model_used = ""
        key_masked = ""

        # ReAct loop
        for iteration in range(self.MAX_ITERATIONS):
            try:
                response_msg = groq_client.chat_completion(
                    messages=working_messages,
                    tools=COPILOT_TOOLS,
                    tool_choice="auto",
                    temperature=0.2,
                )
            except Exception as e:
                logger.error("Groq chat completion failed: %s", e)
                return {
                    "reply": f"Campus Copilot is momentarily reconnecting to the campus network: {e}. Please try again in a moment.",
                    "cards": collected_cards,
                    "tool_calls_executed": tools_executed,
                    "model_used": "fallback",
                    "key_used_masked": "***",
                }

            model_used = response_msg.get("_model_used", model_used)
            key_masked = response_msg.get("_key_used_masked", key_masked)
            tool_calls = response_msg.get("tool_calls")

            # If no tool calls, the model provided its final response
            if not tool_calls:
                content = response_msg.get("content") or ""
                return {
                    "reply": content.strip(),
                    "cards": collected_cards,
                    "tool_calls_executed": tools_executed,
                    "model_used": model_used,
                    "key_used_masked": key_masked,
                }

            # If tool calls were generated, execute them and feed back into conversation
            clean_assistant_msg = {
                "role": "assistant",
                "content": response_msg.get("content") or None,
                "tool_calls": tool_calls,
            }
            working_messages.append(clean_assistant_msg)

            for tc in tool_calls:
                fn = tc.get("function", {})
                fn_name = fn.get("name", "")
                raw_args = fn.get("arguments", "{}")
                call_id = tc.get("id", f"call_{iteration}")

                try:
                    parsed_args = json.loads(raw_args) if isinstance(raw_args, str) else raw_args
                except Exception:
                    parsed_args = {}

                tools_executed.append(fn_name)
                logger.info("Executing Copilot tool: %s with args: %s", fn_name, parsed_args)

                tool_result, ui_card = execute_tool(fn_name, parsed_args, user)
                if ui_card:
                    collected_cards.append(ui_card)

                working_messages.append({
                    "role": "tool",
                    "tool_call_id": call_id,
                    "name": fn_name,
                    "content": json.dumps(tool_result),
                })

        # Fallback if iterations exhausted
        return {
            "reply": "I have processed your campus request. Please see the details above or let me know if you need anything else!",
            "cards": collected_cards,
            "tool_calls_executed": tools_executed,
            "model_used": model_used,
            "key_used_masked": key_masked,
        }


copilot_agent = CampusCopilotAgent()
